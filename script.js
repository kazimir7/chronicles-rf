/* ==========================================================================
   Живой Поиск с подсветкой результатов
   ========================================================================== */
function initSearch() {
  const searchInput = document.getElementById('global-search');
  if (!searchInput) return;

  searchInput.addEventListener('input', (e) => {
    const query = e.target.value.toLowerCase().trim();
    if (!query) {
      renderChronology();
      return;
    }

    const container = document.getElementById('chronology-container');
    if (!container) return;

    const matched = appState.allEventsFlat.filter(ev => 
      ev.title.toLowerCase().includes(query) ||
      ev.text.toLowerCase().includes(query) ||
      ev.date.toLowerCase().includes(query) ||
      ev.figures.toLowerCase().includes(query) ||
      ev.source.toLowerCase().includes(query)
    );

    if (matched.length === 0) {
      container.innerHTML = `
        <div style="text-align: center; padding: 50px 20px; color: var(--text-dim); background: var(--bg-card); border-radius: var(--radius-lg); border: 1px solid var(--border-subtle);">
          🔍 По запросу «<strong>${query}</strong>» ничего не найдено.<br>
          Попробуйте поискать: <em>Крым, Конституция, Петр I, 1945, Мюнхен, СВО, Рюрик</em>.
        </div>
      `;
      return;
    }

    container.innerHTML = `
      <div style="margin-bottom: 24px; color: var(--gold-light); font-weight: 700;">
        Найдено исторических материалов: ${matched.length}
      </div>
      <div class="events-timeline">
        ${matched.map(ev => `
          <div class="event-entry cat-${ev.category}">
            <div class="event-meta">
              <span class="event-date">📅 ${ev.date}</span>
              <span class="event-cat-tag">${ev.categoryName} • ${ev.eraTitle}</span>
            </div>
            <h4 class="event-title">${highlightQuery(ev.title, query)}</h4>
            <p class="event-text">${highlightQuery(ev.text, query)}</p>
            <div class="event-footer-actions">
              <span class="event-source-badge">📜 ${highlightQuery(ev.source, query)}</span>
              <div class="event-action-btns">
                <button class="btn-event-detail" onclick="openResearchModal('${ev.id}')">
                  📖 Исследовать подробно
                </button>
                <button class="btn-bookmark-item ${isBookmarked(ev.id) ? 'saved' : ''}" onclick="toggleBookmark('${ev.id}')">
                  ${isBookmarked(ev.id) ? '★' : '☆'}
                </button>
              </div>
            </div>
          </div>
        `).join('')}
      </div>
    `;
  });

  // Быстрые теги поиска
  document.querySelectorAll('.search-tag-pill').forEach(pill => {
    pill.onclick = () => {
      const tag = pill.getAttribute('data-tag');
      searchInput.value = tag;
      searchInput.dispatchEvent(new Event('input'));
      document.getElementById('chronology').scrollIntoView({ behavior: 'smooth' });
    };
  });
}

function highlightQuery(text, query) {
  if (!query || !text) return text;
  const regex = new RegExp(`(${query})`, 'gi');
  return text.replace(regex, '<mark style="background: rgba(212, 175, 55, 0.45); color: #fff; padding: 1px 4px; border-radius: 3px;">$1</mark>');
}
