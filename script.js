function openBookmarksDrawer() {
  const drawer = document.getElementById('bookmarks-drawer');
  const backdrop = document.getElementById('drawer-backdrop');
  if (drawer && backdrop) {
    renderBookmarksList();
    drawer.classList.add('open');
    backdrop.classList.add('open');
  }
}

function closeBookmarksDrawer() {
  const drawer = document.getElementById('bookmarks-drawer');
  const backdrop = document.getElementById('drawer-backdrop');
  if (drawer && backdrop) {
    drawer.classList.remove('open');
    backdrop.classList.remove('open');
  }
}

function isBookmarked(id) {
  return appState.bookmarks.includes(id);
}

function toggleBookmark(id, isDoc = false) {
  const idx = appState.bookmarks.indexOf(id);
  if (idx === -1) {
    appState.bookmarks.push(id);
  } else {
    appState.bookmarks.splice(idx, 1);
  }

  localStorage.setItem('chronicles_bookmarks', JSON.stringify(appState.bookmarks));
  updateBookmarkCounter();
  renderChronology();
  renderDocuments();
}

function updateBookmarkCounter() {
  const counter = document.getElementById('bookmark-counter');
  if (counter) counter.innerText = appState.bookmarks.length;
}

function renderBookmarksList() {
  const listContainer = document.getElementById('drawer-bookmarks-content');
  if (!listContainer) return;

  if (appState.bookmarks.length === 0) {
    listContainer.innerHTML = `
      <div style="text-align: center; color: var(--text-dim); padding: 40px 10px;">
        ⭐ Закладок пока нет.<br>Нажмите «В закладки» на карточке любого события или документа, чтобы сохранить его в свой архив.
      </div>
    `;
    return;
  }

  const items = appState.bookmarks.map(id => {
    const ev = appState.allEventsFlat.find(e => e.id === id);
    if (ev) {
      return `
        <div class="bookmark-entry-card">
          <span style="font-size: 0.75rem; color: var(--gold-primary); font-weight: 700;">📅 ${ev.date}</span>
          <strong style="font-size: 0.95rem; color: var(--text-primary);">${ev.title}</strong>
          <div style="display: flex; justify-content: space-between; margin-top: 8px;">
            <button class="btn-event-detail" style="font-size: 0.75rem; padding: 4px 10px;" onclick="closeBookmarksDrawer(); openResearchModal('${ev.id}')">
              Исследовать &rarr;
            </button>
            <button style="background: none; border: none; color: #ef4444; cursor: pointer; font-size: 0.8rem;" onclick="toggleBookmark('${ev.id}'); renderBookmarksList();">
              Удалить
            </button>
          </div>
        </div>
      `;
    }

    const doc = MUSEUM_DB.documents.find(d => d.id === id);
    if (doc) {
      return `
        <div class="bookmark-entry-card">
          <span style="font-size: 0.75rem; color: var(--azure-accent); font-weight: 700;">📜 Документ • ${doc.date}</span>
          <strong style="font-size: 0.95rem; color: var(--text-primary);">${doc.title}</strong>
          <div style="display: flex; justify-content: space-between; margin-top: 8px;">
            <a href="${doc.url}" target="_blank" class="doc-link" style="font-size: 0.78rem;">
              Оригинал &rarr;
            </a>
            <button style="background: none; border: none; color: #ef4444; cursor: pointer; font-size: 0.8rem;" onclick="toggleBookmark('${doc.id}'); renderBookmarksList();">
              Удалить
            </button>
          </div>
        </div>
      `;
    }

    return '';
  }).join('');

  listContainer.innerHTML = items;
}

