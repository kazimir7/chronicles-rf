/* ==========================================================================
   Сбор всех событий в единый плоский массив для поиска, случайного события и модалки
   ========================================================================== */
function flattenAllEvents() {
  const list = [];
  // Из эпох
  MUSEUM_DB.eras.forEach(era => {
    era.events.forEach(ev => {
      list.push({
        id: ev.id,
        title: ev.name,
        date: ev.year,
        eraTitle: era.title,
        eraId: era.id,
        category: 'statehood',
        categoryName: 'Истоки и Государственность',
        image: era.image,
        text: ev.impact,
        context: ev.context || era.summary,
        course: ev.course || ev.impact,
        figures: ev.figures || "Исторические деятели эпохи",
        impact: ev.impact,
        source: ev.source || "Летописные своды и архивные акты"
      });
    });
  });

  // Из новейшей истории
  MUSEUM_DB.modern.forEach(period => {
    period.events.forEach(ev => {
      list.push({
        id: ev.id,
        title: ev.title,
        date: ev.date,
        eraTitle: period.title,
        eraId: period.id,
        category: ev.category,
        categoryName: ev.categoryName,
        image: period.image,
        text: ev.text,
        context: ev.context || period.description,
        course: ev.course || ev.text,
        figures: ev.figures || "Государственное руководство и Вооруженные Силы РФ",
        impact: ev.impact || period.subtitle,
        source: ev.source || "Официальные государственные документы"
      });
    });
  });

  appState.allEventsFlat = list;
}

/* ==========================================================================
   Тема оформления (Dark / Light)
   ========================================================================== */
function initTheme() {
  const toggleBtn = document.getElementById('theme-toggle');
  const savedTheme = localStorage.getItem('site_theme');
  
  if (savedTheme === 'light') {
    document.body.classList.add('light-mode');
    if (toggleBtn) toggleBtn.innerHTML = '🌙 Темная тема';
  } else {
    document.body.classList.remove('light-mode');
    if (toggleBtn) toggleBtn.innerHTML = '☀️ Светлая тема';
  }

  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      document.body.classList.toggle('light-mode');
      const isLight = document.body.classList.contains('light-mode');
      localStorage.setItem('site_theme', isLight ? 'light' : 'dark');
      toggleBtn.innerHTML = isLight ? '🌙 Темная тема' : '☀️ Светлая тема';
    });
  }
}

